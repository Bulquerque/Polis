"""Closed enums for S4 valuation, quality, margin, and sizability."""
from enum import StrEnum


class ShockKind(StrEnum):
    SIMPLE_RETURN = "SIMPLE_RETURN"
    LOG_RETURN = "LOG_RETURN"
    ABSOLUTE = "ABSOLUTE"


class LegKind(StrEnum):
    LINEAR = "LINEAR"
    EUROPEAN_OPTION = "EUROPEAN_OPTION"


class OptionType(StrEnum):
    CALL = "CALL"
    PUT = "PUT"


class ValuationQuality(StrEnum):
    FULL_REPRICING = "FULL_REPRICING"
    ANALYTIC_LINEAR = "ANALYTIC_LINEAR"
    DEGRADED = "DEGRADED"
    UNAVAILABLE = "UNAVAILABLE"


class ComponentQuality(StrEnum):
    FULLY_QUALIFIED = "FULLY_QUALIFIED"
    DEGRADED = "DEGRADED"
    UNAVAILABLE = "UNAVAILABLE"
    REJECTED = "REJECTED"


class MarginFidelity(StrEnum):
    EXACT_BROKER_MODEL = "EXACT_BROKER_MODEL"
    SPAN_LIKE_MODEL = "SPAN_LIKE_MODEL"
    CONSERVATIVE_RULE_BASED = "CONSERVATIVE_RULE_BASED"
    UNAVAILABLE = "UNAVAILABLE"


class SizabilityState(StrEnum):
    FULLY_SIZABLE = "FULLY_SIZABLE"
    DEGRADED_SIZABLE = "DEGRADED_SIZABLE"
    NOT_SIZABLE = "NOT_SIZABLE"
    RISK_STATE_INCOMPLETE = "RISK_STATE_INCOMPLETE"


class ConsumptionStatus(StrEnum):
    INTEGRITY_VALIDATED = "INTEGRITY_VALIDATED"
    SEMANTICALLY_CONSUMED = "SEMANTICALLY_CONSUMED"
    PARTIALLY_CONSUMED = "PARTIALLY_CONSUMED"
    RESERVED = "RESERVED"
    NOT_APPLICABLE = "NOT_APPLICABLE"
    CAPABILITY_UNAVAILABLE = "CAPABILITY_UNAVAILABLE"
    REJECTED = "REJECTED"
