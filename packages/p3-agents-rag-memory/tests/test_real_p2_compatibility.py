from __future__ import annotations

import json
import os
from pathlib import Path
import sys

import yaml

from quant_pipeline.phase_03_agents_rag_memory.modules.P3_S1_M01_phase2_handoff_contract_validator import (
    run_module as run_m01,
)
from quant_pipeline.phase_03_agents_rag_memory.modules.P3_S1_M02_source_quality_context_guard import (
    run_module as run_m02,
)


def _resolve_real_p2_package(configured_root: Path) -> Path | None:
    """Resolve the real P2 package across supported repository directory layouts.

    The integration environment may expose the repository as either
    ``New Version`` or ``New Version.sanitized``.  Resolution is bounded to
    the configured path and its immediate parent; it never scans arbitrary
    filesystem locations.
    """
    relative = Path(
        "phase_02_extracted/phase_02_quality_pit_agent_package_RC4_1"
    )
    candidates = [configured_root / relative]

    parent = configured_root.parent
    for sibling_name in ("New Version", "New Version.sanitized"):
        sibling = parent / sibling_name / relative
        if sibling not in candidates:
            candidates.append(sibling)

    # Also accept callers that pass the package root directly.
    candidates.append(configured_root)

    for candidate in candidates:
        package_marker = (
            candidate
            / "src/quant_pipeline/phase_02_quality_pit/modules"
            / "P2_S6_M02_multi_phase_handoff_packager.py"
        )
        if package_marker.is_file():
            return candidate.resolve()
    return None


def _fixture(root: Path) -> dict[str, object]:
    return json.loads(
        (root / "fixtures/external_compat/p2_real_packager_fixture.json").read_text(
            encoding="utf-8"
        )
    )


def _validate(root: Path, payload: dict[str, object]) -> tuple[dict[str, object], dict[str, object]]:
    quality_policy = yaml.safe_load(
        (root / "config/governance/SOURCE_QUALITY_POLICY.yaml").read_text(
            encoding="utf-8"
        )
    )
    handoff = run_m01(payload)["outputs"]["validated_phase2_handoff"]
    output = run_m02(
        {
            "validated_phase2_handoff": handoff,
            "source_quality_panel": payload["source_quality_panel"],
            "source_quality_policy_config": quality_policy,
        }
    )["outputs"]["validated_context_inputs"]
    return handoff, output


def test_integrated_foundation_accepts_vendored_real_p2_packager_fixture(root: Path) -> None:
    """Always-run compatibility gate based on outputs generated by the real P2 packager."""
    handoff, output = _validate(root, _fixture(root))
    assert handoff["validation_status"] == "READY"
    assert output["summary"]["rejected"] == 0


def test_real_p2_packager_matches_vendored_fixture_when_repository_is_available(root: Path) -> None:
    """Regenerate the fixture from the connected repository when NEW_VERSION_ROOT is provided."""
    new_version_root = os.environ.get("NEW_VERSION_ROOT")
    if not new_version_root:
        # The vendored real-packager fixture above remains the mandatory standalone gate.
        return

    configured_root = Path(new_version_root)
    p2 = _resolve_real_p2_package(configured_root)
    if p2 is None:
        # The always-run vendored fixture test remains the compatibility gate
        # when the connected repository is not materialized in this runtime.
        return
    p2_src = str(p2 / "src")
    sys.path.insert(0, p2_src)
    try:
        import quant_pipeline

        quant_pipeline.__path__.append(str(p2 / "src/quant_pipeline"))
        from quant_pipeline.phase_02_quality_pit.modules._p2_semantic_helpers import artifact
        from quant_pipeline.phase_02_quality_pit.modules.P2_S6_M02_multi_phase_handoff_packager import (
            run_module as package_handoffs,
        )

        fixture = _fixture(root)
        required_names = [
            "clean_context_source_panel",
            "clean_document_panel",
            "clean_event_reference_panel",
            "source_quality_panel",
            "quality_report_phase_2",
            "clean_underlying_panel",
            "clean_underlying_trade_panel",
            "clean_macro_br_panel",
            "clean_macro_us_panel",
            "clean_benchmark_panel",
            "clean_calendar_panel",
            "clean_corporate_actions_panel",
            "clean_option_quotes_panel",
            "clean_option_contract_panel",
            "clean_cost_reference_panel",
            "clean_liquidity_reference_panel",
        ]
        data = {
            key: fixture[key]
            for key in (
                "clean_context_source_panel",
                "clean_document_panel",
                "clean_event_reference_panel",
                "source_quality_panel",
            )
        }
        data["quality_report_phase_2"] = {
            "artifact_id": "quality-report-1",
            "created_at": "2026-07-27T23:00:00Z",
            "lineage_id": "lin-qr",
            "pipeline_version": "V14.1-RC4.1",
            "status": "PASS",
            "target_readiness": {},
            "records": [],
        }
        for name in required_names:
            data.setdefault(
                name,
                artifact(
                    name,
                    [{"id": f"{name}-1", "lineage_id": f"lin-{name}"}],
                    {"created_at": "2026-07-27T23:00:00Z"},
                ),
            )
        regenerated = package_handoffs(
            data,
            {"created_at": "2026-07-27T23:00:00Z"},
        )["outputs"]
        live_payload = {
            **{key: fixture[key] for key in data if key in fixture},
            "context_handoff_manifest": regenerated["context_handoff_manifest"],
            "phase3_handoff_manifest": regenerated["phase3_handoff_manifest"],
        }
        handoff, output = _validate(root, live_payload)
        assert handoff["validation_status"] == "READY"
        assert output["summary"]["rejected"] == 0
    finally:
        sys.path = [entry for entry in sys.path if entry != p2_src]
